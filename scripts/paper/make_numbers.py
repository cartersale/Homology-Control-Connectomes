#!/usr/bin/env python
"""Write every number quoted in the paper text as a LaTeX macro.

    python scripts/paper/make_numbers.py --run canonical-2026-10
    python scripts/paper/make_numbers.py --run results --check

Writes <run>/paper/numbers.tex (\\newcommand per number), key_results.json
(unrounded values, for tests/test_paper_numbers.py) and numbers.md (macro ->
source -> draft location, for replacing hard-coded numbers in the manuscript).
``--check`` confirms each number's printed text appears on the draft line it
is quoted from (the manuscript is not part of the repository; pass --paper).
"""

from __future__ import annotations

import argparse
import importlib
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[1]
sys.path.insert(0, str(HERE))
sys.path.insert(0, str(REPO_ROOT / "src"))

from hoc.runs import is_legacy, reader_run_dir, stage_from_argv, writable_root  # noqa: E402

MODULES = ["numbers_main", "numbers_supp"]
STAGE = "paper/numbers"
DEFAULT_PAPER = REPO_ROOT / "paper" / "network_neuro_resubmission"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--run", default=None)
    parser.add_argument("--overwrite", action="store_true")
    parser.add_argument("--check", action="store_true", help="Check each number against the draft text.")
    parser.add_argument("--paper", type=Path, default=DEFAULT_PAPER, help="Manuscript folder for --check.")
    return parser.parse_args()


def collect(res: Path) -> list:
    numbers = []
    for name in MODULES:
        numbers.extend(importlib.import_module(name).collect(res))
    names = [n.name for n in numbers]
    dupes = sorted({n for n in names if names.count(n) > 1})
    assert not dupes, f"duplicate macro names: {dupes}"
    bad = [n for n in names if not re.fullmatch(r"[A-Za-z]+", n)]
    assert not bad, f"macro names must be letters only: {bad}"
    return numbers


def write(numbers: list, out: Path) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    tex = ["% Generated by scripts/paper/make_numbers.py -- do not edit."]
    for n in numbers:
        tex.append(f"\\newcommand{{\\{n.name}}}{{{n.text}}}  % {n.source}")
    (out / "numbers.tex").write_text("\n".join(tex) + "\n")
    (out / "key_results.json").write_text(
        json.dumps({n.name: {"value": n.value, "text": n.text} for n in numbers}, indent=1, sort_keys=True) + "\n"
    )
    md = ["| Macro | Text | Draft | Where | Source |", "| --- | --- | --- | --- | --- |"]
    for n in numbers:
        md.append(f"| `\\{n.name}` | {n.text} | {n.draft or ''} | {', '.join(n.where)} | {n.source} |")
    (out / "numbers.md").write_text("\n".join(md) + "\n")
    return [out / "numbers.tex", out / "key_results.json", out / "numbers.md"]


def check(numbers: list, paper: Path) -> int:
    problems = 0
    for n in numbers:
        expected = n.draft if n.draft is not None else n.text
        for where in n.where:
            file, line = where.rsplit(":", 1)
            lines = (paper / file).read_text().splitlines()
            text = lines[int(line) - 1]
            if expected not in text:
                problems += 1
                print(f"NOT FOUND  \\{n.name}: {expected!r} on {where}: {text.strip()[:140]}")
        if n.draft is not None:
            print(f"MISMATCH   \\{n.name}: draft says {n.draft!r}, saved result gives {n.text!r} ({', '.join(n.where)})")
    print(f"{len(numbers)} numbers, {problems} not found on their draft line")
    return problems


def main() -> None:
    args = parse_args()
    argv = ["--run", args.run] if args.run else []
    run_dir = reader_run_dir(argv)
    out = writable_root(run_dir) / "paper"
    ctx = None
    if not is_legacy(run_dir):
        ctx = stage_from_argv(STAGE, argv=argv + (["--overwrite"] if args.overwrite else []))
        ctx.require_stage("paper/tables")
        ctx.begin()
    numbers = collect(run_dir / "revision")
    written = write(numbers, out)
    print(f"wrote {len(numbers)} numbers to {out}")
    if ctx is not None:
        ctx.finish(outputs=written)
    if args.check:
        sys.exit(1 if check(numbers, args.paper) else 0)


if __name__ == "__main__":
    main()
